// Keeps the existing page JSX and validation paths as the single source of truth.
// Only reviewed loader statements move behind the authenticated JSON API.
import fs from 'node:fs';
import path from 'node:path';
import ts from 'typescript';
const root = path.resolve(import.meta.dirname, '..');
const spec = JSON.parse(fs.readFileSync(path.join(root, 'frontend/tools/pages.json'), 'utf8'));
const generated = path.join(root, 'frontend/generated');
const staticAssets = path.join(root, 'frontend/public');
fs.mkdirSync(staticAssets, {recursive:true});
for(const entry of fs.readdirSync(path.join(root,'public'),{withFileTypes:true})) {
  if(entry.name==='uploads'||entry.name.startsWith('.'))continue;
  if(entry.isDirectory()&&entry.name!=='fonts')continue;
  fs.cpSync(path.join(root,'public',entry.name),path.join(staticAssets,entry.name),{recursive:true});
}
fs.mkdirSync(path.join(generated, 'views'), { recursive: true });
const write = (file, text) => { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, text); };
const parse = (file, text) => ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
const absoluteImports = (text, sourceFile) => text.replace(/(from\s+["']|import\s+["'])(\.[^"']+)(["'])/g, (_, a, name, b) => {
  const target = path.resolve(path.dirname(sourceFile), name);
  return a + '@/' + path.relative(path.join(root, 'src'), target).replaceAll('\\', '/') + b;
});
const registry = [], routes = [];
let index = 0;
for (const [id, config] of Object.entries(spec)) {
  const file = path.join(root, 'src/app', id, 'page.tsx');
  const text = fs.readFileSync(file, 'utf8');
  const source = parse(file, text);
  const fn = source.statements.find(n => ts.isFunctionDeclaration(n) && n.modifiers?.some(m => m.kind === ts.SyntaxKind.DefaultKeyword));
  if (!fn?.body) throw new Error('Missing page function: ' + id);
  const statements = [...fn.body.statements];
  const returnIndex = statements.findIndex(ts.isReturnStatement);
  const prefix = statements.slice(0, returnIndex);
  for (const position of config.remove) if (!prefix[position]) throw new Error('Loader statement changed: ' + id + ' #' + position);
  const loaderFile = path.join(path.dirname(file), 'client-loader.generated.tsx');
  const key = 'page_' + index++;
  if (config.remove.length) {
    let signature = fn.getText(source).slice(0, fn.body.getStart(source) - fn.getStart(source))
      .replace(/export\s+default\s+(async\s+)?function\s+\w+/, 'export async function loadClientPage');
    if(id==='(auth)/login') signature += ': Promise<{user: import("@/lib/session").SessionUser|null}> ';
    const loader = text.slice(0, fn.getStart(source)) + signature + '{\n' +
      prefix.map(s => s.getText(source)).join('\n') + '\nreturn {' + config.data.join(',') + '};\n}' + text.slice(fn.end);
    write(loaderFile, '/* eslint-disable @typescript-eslint/no-unused-vars */\n// Generated by scripts/generate-client-pages.mjs. Do not edit.\n' + loader);
    registry.push(JSON.stringify(id) + ': { access: ' + JSON.stringify(id.startsWith('admin') ? 'admin' : id.startsWith('(app)') ? 'user' : 'public') +
      ', load: async (props: ClientPageProps) => (await import(' +
      JSON.stringify('@/app/' + id + '/client-loader.generated') + ')).loadClientPage(' + (fn.parameters.length ? 'props as never' : '') + ') }');
  }
  const declaration = 'export default async function ' + fn.name.text + '(props: import("@client/types").ClientPageProps) ';
  const fetch = config.remove.length ? '\nconst {' + config.data.join(',') + '} = await loadPage<Awaited<ReturnType<typeof import(' +
    JSON.stringify('@/app/' + id + '/client-loader.generated') + ').loadClientPage>>>(' +
    JSON.stringify(id) + ', props);\n' : '';
  const client = text.slice(0, fn.getStart(source)) + declaration + '{\nconst {params,searchParams}=props;\n' + fetch +
    prefix.filter((_, i) => !config.remove.includes(i)).map(s => s.getText(source)).join('\n') +
    '\n' + statements.slice(returnIndex).map(s => s.getText(source)).join('\n') + '\n}' + text.slice(fn.end);
  write(path.join(generated, 'views', key + '.tsx'), '// Generated from src/app/' + id + '/page.tsx.\n' +
    'import {loadPage} from "@client/api";\n' + absoluteImports(client, file));
  const route = '/' + id.split('/').filter(s => !s.startsWith('(')).join('/');
  routes.push('{path:' + JSON.stringify(route) + ',id:' + JSON.stringify(id) +
    ',layout:' + JSON.stringify(id.startsWith('admin') ? 'admin' : id.startsWith('(app)') ? 'user' : id.startsWith('(auth)') ? 'auth' : 'public') +
    ',guestData:' + JSON.stringify(config.guestData ?? (config.remove.length ? null : {})) +
    ',load:()=>import("./views/' + key + '.tsx")}');
}
write(path.join(root, 'src/server/client-registry.generated.ts'),
  '// Generated; access is checked again inside every loader.\n' +
  'export type ClientPageProps={params:Promise<Record<string,string>>,searchParams:Promise<Record<string,string|string[]|undefined>>};\n' +
  'export const clientPages = {\n' + registry.join(',\n') + '\n};\n');
write(path.join(generated, 'routes.ts'), 'export const routes=[\n' + routes.join(',\n') + '\n].sort((a,b)=>a.path.split("/").filter(s=>s.startsWith("[")).length-b.path.split("/").filter(s=>s.startsWith("[")).length);\n');
// Reuse the exact shell markup while supplying server-calculated badge counts.
const shellFile = path.join(root, 'src/components/app-shell.tsx');
let shell = fs.readFileSync(shellFile, 'utf8');
const shellSource = parse(shellFile, shell);
const shellFn = shellSource.statements.find(n => ts.isFunctionDeclaration(n) && n.name?.text === 'AppShell');
const firstUI = shellFn.body.statements.findIndex(s => s.getText(shellSource).startsWith('const switchLink'));
shell = shell.slice(0, shellFn.body.getStart(shellSource) + 1) +
  '\nconst {unread,counts}=runtime.shell ?? {unread:0,counts:{}};\n' +
  shellFn.body.statements.slice(firstUI).map(s => s.getText(shellSource)).join('\n') + '\n}' + shell.slice(shellFn.end);
shell = shell.replace('export async function AppShell', 'export function AppShell');
write(path.join(generated, 'app-shell.tsx'), 'import {runtime} from "@client/api";\n' + absoluteImports(shell, shellFile));
// An explicit allowlist; the browser cannot choose arbitrary modules/functions.
const actionModules = ['(auth)/actions','(app)/reports/actions','(app)/claims/actions','(app)/matches/actions','(app)/notifications/actions','(app)/profile/actions','admin/actions'];
const actionEntries = [];
for (const actionModule of actionModules) {
  const filename = path.join(root,'src/app', actionModule + '.ts');
  const source = parse(filename, fs.readFileSync(filename,'utf8'));
  for (const n of source.statements) {
    if (ts.isFunctionDeclaration(n) && n.modifiers?.some(m=>m.kind===ts.SyntaxKind.ExportKeyword)) {
      const name=n.name.text;
      actionEntries.push(JSON.stringify(actionModule + ':' + name) + ': async (args: unknown[]) => {const mod=await import(' +
        JSON.stringify('@/app/' + actionModule) + '); return (mod.' + name + ' as (...args: never[])=>Promise<unknown>)(...args as never[]);}');
    }
  }
}
write(path.join(root,'src/server/client-actions.generated.ts'),
  '// Generated action allowlist. Every action keeps its own permission checks.\nexport const clientActions={\n' + actionEntries.join(',\n') + '\n};\n');
console.log('Prepared '+routes.length+' static page views and '+actionEntries.length+' guarded actions.');
